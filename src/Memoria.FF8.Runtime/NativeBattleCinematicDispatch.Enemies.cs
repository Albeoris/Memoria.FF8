        [(220, "vm_table", 295)] = (0xABB790, 0xB2E430),
        [(220, "vm_table", 309)] = (0xABAB20, 0xB2D7C0),
    }.ToFrozenDictionary();

    private static bool TryRequireEnemySlot(int effect, string table, int index, uint handler, out uint canonical)
    {
        if (effect is 232 or 238 or 241 or 249 or 256)
        {
            if (!EnemySlotBindings.TryGetValue((effect, table, index), out (uint Handler, uint Canonical) selectedDomain) || handler != selectedDomain.Handler)
            {
                throw new NotSupportedException("Native cinematic enemy slot is outside its selected handler domain.");
            }
            canonical = selectedDomain.Canonical;
            return true;
        }
        uint exact = (effect, table, index) switch
        {
            (77, "vm_table", 0xAF) => 0xB39820,
            (211, "vm_table", 0xAF) => 0xAD29D0,
            (219, "vm_table", 0xB3) => 0xAC7800,
            (208, "draw_table", 47) => 0xAD9BF0,
            (208, "draw_table", 52) => 0xAD9160,
            (211, "draw_table", 47) => 0xACE7B0,
            (219, "draw_table", 49) => 0xAC26B0,
            (219, "draw_table", 67) => 0xAC2230,
            (75, "draw_table", 66) => 0xB429A0,
            _ => 0
        };
        if (exact != 0)
        {
            if (handler != exact)
            {
                throw new NotSupportedException("Native cinematic enemy slot differs from its selected callback.");
            }
            canonical = index == 0xAF && table == "vm_table" ? 0xB52F20 : exact;
            return true;
        }
        if (EnemyNoOps.TryGetValue((effect, table, index), out uint expected))
        {
            if (handler != expected)
            {
                throw new NotSupportedException("Native cinematic enemy slot differs from its original no-op callback.");
            }
            canonical = handler;
            return true;
        }
        if (EnemySlotBindings.TryGetValue((effect, table, index), out (uint Handler, uint Canonical) selected))
        {
            if (handler != selected.Handler)
            {
                throw new NotSupportedException("Native cinematic enemy slot differs from its original callback.");
            }
            canonical = selected.Canonical;
            return true;
        }
        canonical = 0;
        return false;
    }
