    private static readonly FrozenDictionary<uint, uint> Effect264Aliases = Effect264Slots.Values.Where(pair => pair.Handler != pair.Canonical).Distinct().ToFrozenDictionary(pair => pair.Handler, pair => pair.Canonical);

    private static uint RequireEffect264Slot(string table, int index, uint handler)
    {
        if (!Effect264Slots.TryGetValue((table, index), out var selected) || handler != selected.Handler)
        {
            throw new NotSupportedException($"Native cinematic effect 264 table {table} slot {index:X} requires its selected handler contract.");
        }
        return selected.Canonical;
    }
